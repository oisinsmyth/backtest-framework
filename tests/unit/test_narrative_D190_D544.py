"""Every number in `docs/results/D190-D544.md` is pinned to the artifact it came from (D545).

The page is **hand-written**, which makes it the odd one out in `docs/results/` — every other `.md`
there is emitted by a runner, prose and all. That matters for one specific reason:
`tests/unit/test_quoted_counts_are_current.py` lists `docs/results/` as FROZEN with the reason
*"study ledgers emitted by a runner; regenerating the study rewrites them"*. A hand-written page
dropped in that directory inherits a no-gate exemption written for files a runner owns — **nothing
would ever check its numbers, and nothing would ever rewrite them either.**

So the page brings its own gate, and this is it.

WHY ANCHOR TO `data/*.json` AND NOT TO ANOTHER DOCUMENT
-------------------------------------------------------
`tests/unit/test_writeup.py` — the pattern this file follows — checks `docs/writeup.md` against
`docs/results/*.md`, which are themselves prose. An artifact is regenerated by a runner and already
gated by `scripts/build_data_manifest.py --verify`, so it is the stronger source: if a study is
re-run and a headline moves, the JSON moves and this file goes red.

THE FLOOR, WHICH `test_writeup.py` DOES NOT HAVE
-------------------------------------------------
A `@pytest.mark.parametrize` over an empty list collects nothing and fails nothing. Measured on
`test_writeup.py` before this file existed: emptying its `ANCHORS` takes it from **29 passed to
"3 passed, 1 skipped", exit code 0** — its twenty-six anchor checks vanish silently, in the gate
whose entire job is keeping a document honest. That is the empty-scan defect, and the same floor is
added there.
"""

