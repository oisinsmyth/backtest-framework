@pytest.fixture(scope="module")
def page() -> str:
    return _normalized(PAGE)


def test_the_page_exists_and_says_what_it_is(page):
    """A hand-written page in a runner-owned directory must say so on its face, and carry the
    date that stands in for the regeneration it will never get."""
    assert "Hand-written" in page
    assert "2026-09-18" in page


def test_the_anchor_list_has_not_been_emptied():
    """THE FLOOR. `@pytest.mark.parametrize` over `[]` collects nothing and fails nothing, which
    is how a gate becomes decorative without anyone noticing."""
    assert len(ANCHORS) >= MINIMUM_ANCHORS, (
        f"{len(ANCHORS)} anchors, below the floor of {MINIMUM_ANCHORS}. Either the page lost its "
        f"evidence or this list was trimmed; both read as a pass from the parametrized test."
    )


@pytest.mark.parametrize("quoted,what,recompute", ANCHORS, ids=[a[1] for a in ANCHORS])
def test_every_quoted_number_matches_its_artifact(page, quoted, what, recompute):
    """The number on the page, and the number in `data/`, must be the same string."""
    measured = recompute()
    assert measured == quoted, (
        f"{what}: the artifact now reads {measured!r} but the page quotes {quoted!r}. A study was "
        f"re-run and a headline moved — update docs/results/D190-D544.md, it is now lying."
    )
    assert quoted in page, f"docs/results/D190-D544.md no longer quotes {quoted!r} for {what}"


def test_the_page_states_that_nothing_is_at_capital(page):
    """The directive that shaped this page: a market-findings framing invites 'so what did you
    make', and the answer belongs in the opening rather than the footer."""
    assert "Nothing here is at capital" in page
    head = page[: page.index("## Three findings about trading")]
    assert "at capital" in head, "the disclosure moved below the first finding"


def test_the_page_keeps_the_two_theorems_apart(page):
    """C2b's centre-bias theorem and D373's 2-SE UNRESOLVED band are different claims, and this
    record's own first draft conflated them. The distinction is load-bearing enough to pin."""
    assert "2 SE" in page and "UNRESOLVED" in page
    assert "They are not the same claim." in page


def test_the_unsourceable_numbers_are_named_as_such(page):
    """D466's 0.62 / 0.42 / 0.91 have no committed artifact — they were computed outside the
    runner. The page may quote them ONLY as withdrawn, and must say they cannot be sourced."""
    for orphan in ("0.62", "0.42", "0.91"):
        assert orphan in page, f"the page stopped naming the withdrawn figure {orphan}"
    assert "no artifact" in page
    assert re.search(r"cannot be sourced", page), "the page must say why those three differ"
