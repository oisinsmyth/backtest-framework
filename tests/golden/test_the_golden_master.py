# --------------------------------------------------------------- the closed-book calculator


def recompute(scenario: dict) -> list[dict]:
    """Walk the scenario bar by bar in stdlib arithmetic.

    Must not use `backtest_framework`; a calculator that called the cost bricks would agree
    with them by construction. `test_the_closed_book_calculator_never_reaches_for_the_engine`
    enforces this.

    Order of operations, as in the hand file's "Engine order per bar" line: snapshot at this
    bar's close on the previous bar's cash -> per-leg borrow and dividend -> portfolio
    margin -> re-size at the post-carry NAV -> fill at the close.
    """
    per_share = scenario["commission"]["per_share"]
    minimum = scenario["commission"]["minimum"]
    cap_frac = scenario["commission"]["cap_frac"]
    bps = scenario["spread_bps"]
    ex_date = datetime.fromisoformat(scenario["dividend"]["ex"])
    per_share_dividend = scenario["dividend"]["per_share"]

    cash = scenario["starting_cash"]
    qty = 0.0
    previous: datetime | None = None
    out: list[dict] = []

    for index, (raw_ts, price, weight) in enumerate(
        zip(scenario["timestamps"], scenario["closes"], scenario["weights"])
    ):
        timestamp = datetime.fromisoformat(raw_ts)
        days = None if previous is None else (timestamp - previous).days
        borrow = margin_interest = dividend = 0.0
        short_notional = margin_base = 0.0

        if previous is None:
            # No previous bar, no carry step: the sizing NAV is the starting cash.
            nav_snapshot = cash + qty * price
        else:
            nav_snapshot = cash + qty * price
            if qty != 0.0:
                short_notional = -qty * price if qty < 0.0 else 0.0
                borrow = scenario["borrow_annual"] * short_notional * days / 365.0
                cash -= borrow
                if previous < ex_date <= timestamp:
                    # A short pays the dividend to the lender: negative on a negative
                    # quantity.
                    dividend = qty * per_share_dividend
                    cash += dividend
            margin_base = max(abs(qty) * price - nav_snapshot, 0.0)
            margin_interest = scenario["margin_annual"] * margin_base * days / 365.0
            cash -= margin_interest

        nav_post_carry = cash + qty * price
        desired = float(round(weight * nav_post_carry / price))  # whole shares
        delta = desired - qty
        notional = abs(delta) * price
        commission = (
            min(max(per_share * abs(delta), minimum), cap_frac * notional) if delta != 0.0 else 0.0
        )
        spread = bps / 10_000.0 * notional
        trade_cost = commission + spread
        cash -= delta * price + trade_cost

        out.append(
            {
                "index": index,
                "timestamp": raw_ts,
                "price": price,
                "days": days,
                "qty_before": qty,
                "qty_after": desired,
                "delta": delta,
                "notional": notional,
                "commission": commission,
                "spread": spread,
                "trade_cost": trade_cost,
                "short_notional": short_notional,
                "borrow": borrow,
                "margin_base": margin_base,
                "margin_interest": margin_interest,
                "dividend": dividend,
                "nav_snapshot": nav_snapshot,
                "nav_post_carry": nav_post_carry,
                "cash": cash,
                "nav": cash + desired * price,
            }
        )
        qty = desired
        previous = timestamp

    return out


def hand_notation(value: float) -> str:
    """Format a number as the .hand.txt writes it.

    Comma-grouped, at the fewest decimals that reproduce the value, capped at the ten places
    used for carry accruals: `6.4438356164` (borrow), `100,149.6537022380` (final NAV),
    `117,600` (a notional), `-626.50` (the dividend). The JSON carries the file's digits, so
    the round trip is exact.
    """
    for places in range(0, 11):
        text = f"{value:,.{places}f}"
        if float(text.replace(",", "")) == value:
            return text
    return f"{value:,.10f}"


def _numbers(node: object, path: str = "") -> list[tuple[str, float]]:
    """Return every numeric leaf in the ledger with its path.

    `index` is skipped: it is an ordinal, and finding "3" in a document full of dates would
    check nothing.
    """
    if isinstance(node, bool) or node is None:
        return []
    if isinstance(node, (int, float)):
        return [(path, float(node))]
    if isinstance(node, dict):
        return [
            pair
            for key, value in node.items()
            if key != "index"
            for pair in _numbers(value, f"{path}.{key}" if path else key)
        ]
    if isinstance(node, list):
        return [pair for i, item in enumerate(node) for pair in _numbers(item, f"{path}[{i}]")]
    return []


# ------------------------------------------------------------- the ledger against itself


def test_the_closed_book_recomputation_reproduces_every_hand_value():
    """Recompute all 19 fields of all 5 bars from the scenario block in stdlib arithmetic.

    This would catch a JSON that was generated by the engine it is meant to check.
    """
    computed = recompute(SCENARIO)
    assert len(computed) == len(BARS)
    for got, want in zip(computed, BARS):
        assert got["timestamp"] == want["timestamp"]
        for field in LEDGER_FIELDS:
            assert field in want, f"bar {want['index']} has no {field!r} in the hand ledger"
            if want[field] is None:
                assert got[field] is None, f"bar {want['index']}: {field} should be null"
                continue
            assert got[field] == pytest.approx(want[field], rel=TOLERANCE, abs=1e-9), (
                f"bar {want['index']}: recomputed {field}={got[field]!r}, "
                f"hand ledger says {want[field]!r}"
            )


def test_the_closed_book_calculator_never_reaches_for_the_engine():
    """`recompute` must not call into the engine.

    It shares a module with the engine's imports, so a disagreement could be "fixed" by
    calling `IBKRCommission().cost(...)`, which would make the golden master check nothing.
    The check reads the source, since such a calculator would behave identically.
    """
    # Code only, with the docstring and comments removed: a prose mention of the package is
    # not a call.
    tree = ast.parse(textwrap.dedent(inspect.getsource(recompute)))
    function = tree.body[0]
    assert isinstance(function, ast.FunctionDef)
    if ast.get_docstring(function) is not None:
        function.body = function.body[1:]
    source = ast.unparse(function)
    # Two complementary checks. The substring check catches dynamic access
    # (`sys.modules["backtest_framework"]`, `importlib.import_module(...)`), which binds
    # nothing at module scope; it cannot see an alias.
    assert "backtest_framework" not in source

    # The resolved-globals check catches aliases such as
    # `from backtest_framework.costs.equity_bricks import IBKRCommission as _c` followed by
    # `_c(...)`: `getclosurevars` returns objects, and an object reports its defining module.
    # A module-level import check is not possible because the other tests here run the engine.
    _assert_resolves_to_no_engine_object(recompute, seen=set())


def _assert_resolves_to_no_engine_object(func, seen: set) -> None:
    """Assert that no global this function uses, directly or via a helper, is from the package.

    Recurses into same-module helpers, since `getclosurevars` does not.
    """
    if func in seen:
        return
    seen.add(func)
    for name, value in inspect.getclosurevars(func).globals.items():
        module = getattr(inspect.getmodule(value), "__name__", "") or getattr(value, "__module__", "") or ""
        assert not module.startswith("backtest_framework"), (
            f"the closed-book calculator uses {name!r}, which resolves to {module}. It must "
            "reproduce the arithmetic without calling the implementation it checks (the check "
            "is on the object, whatever name it is bound to)."
        )
        if inspect.isfunction(value) and inspect.getmodule(value) is inspect.getmodule(func):
            _assert_resolves_to_no_engine_object(value, seen)


def test_every_hand_value_appears_in_the_hand_file():
    """Every number in the JSON appears in the .hand.txt.

    Uses substring containment rather than parsing the prose, which would break on any
    unanticipated sentence. Containment is a weak check (`6.00` contains `6`); the
    recomputation test is the main one. This catches a value added to the JSON that the
    hand derivation never states.
    """
    prose = HAND_TXT.read_text(encoding="utf-8")
    missing = [
        (path, value, hand_notation(value))
        for path, value in _numbers(HAND)
        if hand_notation(value) not in prose
    ]
    assert not missing, (
        f"{len(missing)} value(s) in the hand JSON are not stated in "
        f"{HAND_TXT.name}: {missing[:6]}"
    )
    # Dates: the hand file writes the year once ("Thu 2026-01-08") and the rest month-day
    # ("Fri 01-09"), so the year is checked once and each bar by the form it is written in.
    years = {raw_ts[:4] for raw_ts in SCENARIO["timestamps"]}
    assert len(years) == 1 and years.pop() in prose
    for raw_ts in SCENARIO["timestamps"] + [SCENARIO["dividend"]["ex"]]:
        month_day = raw_ts.split("T")[0][5:]
        assert month_day in prose, f"{month_day} is not a date the hand derivation mentions"


def test_the_hand_file_is_the_transcription_source_and_says_so():
    """The .hand.txt is the source and the JSON is transcribed from it, not the reverse."""
    assert HAND["transcribed_from"] == "tests/golden/test_the_golden_master.hand.txt"
