"""Golden master: the whole simulator against a hand-computed 5-bar short-side scenario.

Every fill, commission, carry accrual, the dividend debit, and cash and NAV per bar are
asserted line by line. Ground truth is test_the_golden_master.hand.txt, produced by a
standalone calculator that does not import this codebase.

The .hand.json file
-------------------
A fill is reported as `(ts, instrument_id, qty, price, trade_cost)`, where `trade_cost` is
the sum of commission and spread, so fills alone would not catch $6.00 moving from
`IBKRCommission` to `PercentOfNotionalSpread`. Borrow, margin interest and the dividend
reach the result only through the cash and equity curves, which cannot tell them apart.
`BacktestResult` (src/backtest_framework/engine/backtest.py) has no per-brick attribution,
so the decomposition exists only in the hand ledger. `test_the_golden_master.hand.json` is
that ledger in machine-readable form, transcribed by hand from the .hand.txt and not
generated by the engine.

Three tests check the transcription:

1. `test_the_closed_book_recomputation_reproduces_every_hand_value` recomputes all 19
   fields of all 5 bars from the scenario block with stdlib arithmetic.
2. `test_every_hand_value_appears_in_the_hand_file` requires each number, in the
   .hand.txt's own notation, to appear in the .hand.txt.
3. `test_the_cash_curve_carries_the_carry_the_engine_never_reports` reads the carry and
   the dividend from the cash curve and checks their per-bar sum against the ledger.

Borrow and margin interest within one bar cannot be separated from outside the engine:
both are same-sign cash deductions at the same instant. The hand ledger and the
closed-book calculator split them.
"""

