def dividend_grids(panel, g, events_path):
    """Cash dividends on their EX-DATE bar, as three aligned grids.

    Both sidecar shapes are handled exactly as `load_ragged` handles them:
    `["2016-11-08T00:00:00", 0.09]` and `{"date": ..., "amount": ...}`. The same
    filters are applied -- on the grid, positive, live, finite close -- because
    the whole point of `dlog_close` is to REPRODUCE the loader so a disagreement
    is a defect rather than a convention difference.

      amt         cash per share, summed where two land on one bar
      dlog_close  log1p(amt/close), accumulated PER ITEM exactly as the loader
                  does -- two dividends on one bar give log1p(a/c)+log1p(b/c),
                  not log1p((a+b)/c), and the cross-check is exact only if this
                  matches
      dlog_open   log1p(amt/open), the term an OVERNIGHT position actually owes,
                  because the position is entered at close(t) and the drop is
                  taken at the open of t+1

    The open denominator is the exact decomposition for the overnight leg:
    total = (open(t+1) + D) / close(t), which factors as the gap times
    (1 + D/open(t+1)). The loader's close denominator is the same quantity for a
    close-to-close bar and differs from this at second order."""
    amt = np.zeros_like(panel.closes)
    dlog_close = np.zeros_like(panel.closes)
    dlog_open = np.zeros_like(panel.closes)
    ev = json.loads(Path(events_path).read_text(encoding="utf-8"))
    payload = ev.get("dividends", ev) if isinstance(ev, dict) else ev
    pos_of = {d: i for i, d in enumerate(panel.dates)}
    idx_of = {s: i for i, s in enumerate(panel.symbols)}
    applied, open_fallback = 0, 0
    for s, items in (payload.items() if isinstance(payload, dict) else []):
        i = idx_of.get(s)
        if i is None:
            continue
        for it in items:
            if isinstance(it, (list, tuple)):
                d, a = str(it[0])[:10], float(it[1])
            else:
                d = str(it.get("date") or it.get("ex_date") or "")[:10]
                a = float(it.get("amount", it.get("dividend", 0.0)) or 0.0)
            t = pos_of.get(d)
            if t is None or a <= 0.0 or not panel.live[i, t] or np.isnan(panel.closes[i, t]):
                continue
            amt[i, t] += a
            dlog_close[i, t] += math.log1p(a / panel.closes[i, t])
            o = g["open"][i, t]
            if np.isfinite(o) and o > 0:
                dlog_open[i, t] += math.log1p(a / o)
            else:
                dlog_open[i, t] += math.log1p(a / panel.closes[i, t])
                open_fallback += 1
            applied += 1
    return amt, dlog_close, dlog_open, applied, open_fallback


def assert_dividends_match_loader(panel, dlog_close, tol=1e-9):
    """The loader's `total - log_returns` IS its own log1p(amt/close) on every
    ex-date bar. Rebuilding it from an independent parse and asserting equality
    is what stops a silently-dropped symbol understating the charge on exactly
    the falling, high-yield names this book holds."""
    loader = panel.total_log_returns - panel.log_returns
    worst = float(np.max(np.abs(loader - dlog_close)))
    if not np.isfinite(worst) or worst > tol:
        raise AssertionError(
            f"dividend parse disagrees with load_ragged by {worst:.3e} -- refusing "
            "to charge a dividend grid the loader does not recognise")
    return worst, int((loader != 0.0).sum())


