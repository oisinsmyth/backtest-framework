def audit_lag(base, score, n, pos):
    """L1. Re-derive the held set from `score[:, t-1]` and assert it matches.

    Deliberately a SECOND implementation rather than a call into `C.top_n`: the
    point is to disagree with it if it is wrong, and a check that shares the code
    it checks cannot. Returns the number of bars verified; raises on the first
    mismatch."""
    if np.any(base[:, 0] != 0.0):
        raise AssertionError("base column 0 is non-zero; hold_book did not lag")
    checked = 0
    for t in range(1, base.shape[1]):
        q = np.flatnonzero(base[:, t] != 0.0)
        if q.size == 0:
            continue
        if q.size <= n:
            want = q
        else:
            s = score[q, t - 1]                       # EXPLICITLY the prior bar
            s = np.where(np.isfinite(s), s, np.inf)
            want = q[np.argsort(s, kind="stable")[:n]]
        got = np.flatnonzero(pos[:, t] != 0.0)
        if got.size != want.size or not np.array_equal(np.sort(got), np.sort(want)):
            raise AssertionError(
                f"top{n} bar {t}: held set does not match the rank of score[:, t-1]")
        checked += 1
    return checked


def held_rank_pctile(base, score, pos, shift):
    """Mean cross-sectional percentile of the HELD names in the bar's score.

    `shift=1` scores them on `score[:, t-1]`, which is all the book may see;
    `shift=0` on `score[:, t]`. A correctly lagged book sits near the BOTTOM of
    the lagged distribution and nearer the middle of the contemporaneous one.
    The D279 defect inverted exactly that."""
    acc = []
    for t in range(1, base.shape[1]):
        q = np.flatnonzero(base[:, t] != 0.0)
        if q.size < 2:
            continue
        h = np.flatnonzero(pos[:, t] != 0.0)
        if h.size == 0:
            continue
        s = np.where(np.isfinite(score[q, t - shift]), score[q, t - shift], np.inf)
        rank = np.empty(q.size, dtype=float)
        rank[np.argsort(s, kind="stable")] = np.arange(q.size)
        acc.append(rank[np.searchsorted(q, h)] / max(q.size - 1, 1))
    return float(np.concatenate(acc).mean()) if acc else float("nan")


def audit_return_window(panel, cleaned, night, amt, n_samples=AUDIT_SAMPLES, seed=SEED):
    """L2. Recompute the credited return from the RAW bar objects.

    This is the check that proves the earned quantity is the overnight leg. For
    each sampled valid cell it asserts THREE things:

      * `cleaned[sym][k].timestamp` is `panel.dates[t]`      -- the entry bar
      * `cleaned[sym][k+1].timestamp` is `panel.dates[t+1]`  -- the exit bar
      * the value equals `log(bar[k+1].open / bar[k].close)` plus the ex-dividend
        charge at `bar[k+1].open`

    The `k`-th live column of a symbol IS its `k`-th cleaned bar -- `load_ragged`
    writes both from one index vector, and `signals_ragged` already asserts the
    counts agree -- so `searchsorted` maps a grid column to a bar without a
    per-symbol date dict."""
    rng = np.random.default_rng(seed)
    vi, vt = np.nonzero(night["valid"])
    if vi.size == 0:
        raise AssertionError("no valid overnight cells at all")
    take = rng.choice(vi.size, size=int(min(n_samples, vi.size)), replace=False)
    order = np.argsort(vi[take], kind="stable")       # group by symbol, one live-index pass each
    checked, worst, last_i, at = 0, 0.0, -1, None
    for k in take[order]:
        i, t = int(vi[k]), int(vt[k])
        if i != last_i:
            at = np.flatnonzero(panel.live[i])
            last_i = i
        j = int(np.searchsorted(at, t))
        if j + 1 >= at.size or at[j] != t or at[j + 1] != t + 1:
            raise AssertionError(f"{panel.symbols[i]}: valid cell {t} is not two adjacent bars")
        b0, b1 = cleaned[panel.symbols[i]][j], cleaned[panel.symbols[i]][j + 1]
        if b0.timestamp[:10] != panel.dates[t] or b1.timestamp[:10] != panel.dates[t + 1]:
            raise AssertionError(
                f"{panel.symbols[i]}: bar dates {b0.timestamp[:10]}/{b1.timestamp[:10]} "
                f"do not match grid dates {panel.dates[t]}/{panel.dates[t + 1]}")
        want = math.log(b1.bar.open / b0.bar.close)
        a = float(amt[i, t + 1])
        if a > 0:
            want += math.log1p(a / b1.bar.open)
        d = abs(want - float(night["on_log"][i, t]))
        if d > 1e-10:
            raise AssertionError(
                f"{panel.symbols[i]} @ {panel.dates[t]}: credited "
                f"{night['on_log'][i, t]:.10f}, close->next-open is {want:.10f}")
        worst = max(worst, d)
        checked += 1
    return checked, worst


def assert_not_close_to_close(panel, night):
    """L3. The one defect that would be invisible in the output.

    If this file ever reverts to `RP.score`, or if the grid is wired to
    `total_log_returns` by accident, every printed number becomes a
    close-to-close book's and nothing else in the run would say so. Asserted,
    with the correlation and the size ratio printed -- D280 measured the gap at
    51.5% of the body, so a ratio near that is the expected reading."""
    a, b = night["on_log"], panel.total_log_returns
    m = night["valid"] & np.isfinite(b)
    if m.sum() < 1000:
        raise AssertionError("too few comparable cells to verify the earned quantity")
    if np.allclose(a[m], b[m], atol=1e-12):
        raise AssertionError(
            "THE EARNED GRID IS THE CLOSE-TO-CLOSE RETURN. An overnight book does "
            "not earn that; refusing to score.")
    corr = float(np.corrcoef(a[m], b[m])[0, 1])
    ratio = float(np.mean(np.abs(a[m])) / np.mean(np.abs(b[m])))
    return corr, ratio, int(m.sum())


