def overnight_score(panel, pos, night, *, ppy=PPY, rf_annual=RF,
                    borrow_annual=BORROW, start=0, light=False):
    """Score an OVERNIGHT book. Mirrors `RP.score`'s conventions exactly except
    where the construction forbids it -- see the module docstring.

    Kept from `RP.score`, so the numbers are comparable to D256/D279/D281:
      * equal weight over LIVE names, never over `n`
      * `ex = r - long_frac*rf - short_frac*borrow`; rf finances the LONG leg,
        so on a short-only book it is inert and is reported as such
      * one period of borrow per period held, at `expm1(log1p(rate)/ppy)`, which
        for a nightly book is the full annual rate on every night held -- the
        conservative reading, and the right one for a position that is short
        across the settlement

    Replaced, because inheriting it would be wrong:
      * TURNOVER IS `2 * |pos|` EVERY NIGHT. Enter at the close, cover at the
        open: a name held two nights running is two round trips, and
        `|diff(pos)|` would call it zero.
      * `trades` is HELD NAME-NIGHTS. `diff(pos) > 0` counts initiations, which
        on a nightly book undercounts by the mean holding run.
    """
    p = enforce_tradeable(pos, panel, night, start)
    simple, nlive = night["simple"], night["nlive"]

    gross_bar = (p * simple).sum(axis=0) / nlive
    units_bar = (2.0 * np.abs(p)).sum(axis=0) / nlive
    cost_bar = (panel.cost_fraction[:, None] * 2.0 * np.abs(p)).sum(axis=0) / nlive
    r = (gross_bar - cost_bar)[start:]

    lf = float((np.maximum(p, 0.0).sum(axis=0) / nlive)[start:].mean())
    sf = float((np.maximum(-p, 0.0).sum(axis=0) / nlive)[start:].mean())
    rf_p = math.expm1(math.log1p(rf_annual) / ppy)
    bor_p = math.expm1(math.log1p(borrow_annual) / ppy)
    ex = r - lf * rf_p - sf * bor_p
    sd = float(np.std(ex, ddof=1))
    if light:
        return {"excess_sharpe": (float(np.mean(ex)) / sd * math.sqrt(ppy)) if sd > 0 else 0.0,
                "total_return": float(np.cumprod(1.0 + r)[-1] - 1.0)}

    eq = np.cumprod(1.0 + r)
    yrs = len(r) / ppy
    dd = eq / np.maximum.accumulate(eq) - 1.0

    held = p[:, start:] != 0.0
    n_trades = int(held.sum())
    # THE PRIMARY STATISTIC. Signed in the trade's own direction, so a profitable
    # short is POSITIVE. Trade count cancels in `move >= 2c` (D265); this is the
    # left-hand side and `TWO_C_BP` is the right.
    sgn = np.sign(p[:, start:])
    mv = (sgn * simple[:, start:])[held]
    mv_raw = (sgn * night["simple_raw"][:, start:])[held]
    move_bp = float(mv.mean() * 1e4) if n_trades else float("nan")
    move_raw_bp = float(mv_raw.mean() * 1e4) if n_trades else float("nan")

    turn_pooled = float(units_bar[start:].sum())
    paid = float(cost_bar[start:].sum())
    charged_bps = float(np.mean(panel.cost_fraction) * 1e4)
    # THE FEE AT WHICH NET REACHES ZERO, borrow held at its charged rate. Costs
    # enter `ex` linearly through a uniform `cost_fraction`, so this is exact
    # rather than a first-order reading; D264's log form is emitted beside it.
    be = 1e4 * (float(ex.sum()) + paid) / turn_pooled if turn_pooled > 0 else None
    be_log = (1e4 * (1.0 - math.exp(-(float(ex.sum()) + paid) / turn_pooled))
              if turn_pooled > 0 else None)

    pnl = (p[:, start:] * simple[:, start:]).sum(axis=1)
    tot = float(pnl.sum())
    active = (p != 0.0).astype(float)
    entries = int(np.sum(np.diff(active, axis=1, prepend=0.0)[:, start:] > 0.0))

    return {
        "excess_sharpe": (float(np.mean(ex)) / sd * math.sqrt(ppy)) if sd > 0 else 0.0,
        "terminal_multiple": float(eq[-1]),
        "cagr": float(eq[-1] ** (1.0 / yrs) - 1.0) if eq[-1] > 0 else -1.0,
        "total_return": float(eq[-1] - 1.0),
        "vol": float(np.std(r, ddof=1) * math.sqrt(ppy)),
        "max_drawdown": float(dd.min()),
        "worst_bar": float(r.min()),
        "exposure_gross": lf + sf, "exposure_long": lf, "exposure_short": sf,
        "gross_edge_annual": float(np.mean(r)) * ppy,
        # --- the cost bar, D265's form ---
        "mean_move_bp": move_bp,
        "mean_move_bp_raw_gap": move_raw_bp,
        "dividend_drag_bp": (move_raw_bp - move_bp) if n_trades else float("nan"),
        "two_c_bp": TWO_C_BP,
        "move_over_2c": (move_bp / TWO_C_BP) if n_trades else float("nan"),
        "clears_M": bool(n_trades > 0 and move_bp >= TWO_C_BP),
        "breakeven_bps": be, "breakeven_bps_logform": be_log,
        "charged_bps": charged_bps,
        # --- counts. `trades` is HELD NAME-NIGHTS; see the docstring. ---
        "trades": n_trades,
        "entries_diff_based": entries,
        "round_trips_per_name_year": (float(n_trades) / max(int((p[:, start:] != 0).any(axis=1).sum()), 1) / yrs),
        "turnover_units": float((2.0 * np.abs(p[:, start:])).sum()),
        "turnover_units_pooled": turn_pooled,
        "cost_paid_pooled": paid,
        "top_name_share": (float(np.max(pnl) / tot) if tot != 0 else None),
        "rf_is_inert": bool(lf == 0.0),
    }


def overnight_rotation_null(panel, pos, night, *, n_sims, seed, ppy=PPY,
                            rf_annual=RF, borrow_annual=BORROW, start=0):
    """`RP.rotation_null`'s construction against the overnight scorer.

    Rolled WITHIN each symbol's own live window, for the reason `RP` gives:
    rolling across the whole grid places exposure on bars where the name did not
    exist, which the live mask then deletes, silently lowering the null's
    exposure and making the hurdle easier.

    Reseeded from SEED and walking symbols in panel order, so draw `k` uses
    IDENTICAL offsets in every book -- which is what makes the per-draw max
    across books a valid best-of-K floor.

    REPORTED, NOT DECISIVE. R7's corollary; see the pre-registration."""
    rng = np.random.default_rng(seed)
    p0 = enforce_tradeable(pos, panel, night, start)
    windows = [panel.index_of[s] for s in panel.symbols]
    sh, mn = np.empty(n_sims), np.empty(n_sims)
    for k in range(n_sims):
        rot = np.zeros_like(p0)
        for i, (a, b) in enumerate(windows):
            seg = p0[i, a:b + 1]
            if seg.size > 1:
                rot[i, a:b + 1] = np.roll(seg, int(rng.integers(0, seg.size)))
        s = overnight_score(panel, rot, night, ppy=ppy, rf_annual=rf_annual,
                            borrow_annual=borrow_annual, start=start, light=True)
        sh[k], mn[k] = s["excess_sharpe"], s["total_return"]
    return sh, mn


