def night_grids(panel, g, dlog_open):
    """`on_log[:, t]` is the night AFTER the close of bar t. See the module
    docstring for the exact quantity; nothing else in this file defines it.

    `on_raw_log` is the same without the dividend charge, kept so the dividend
    drag on the HELD book can be reported in bp rather than assumed."""
    O, Cl = g["open"], g["close"]
    n, T = Cl.shape
    on = np.zeros((n, T))
    on_raw = np.zeros((n, T))
    valid = np.zeros((n, T), dtype=bool)

    adjacent = panel.live[:, :-1] & panel.live[:, 1:]      # STRICTER than the loader
    c0, o1 = Cl[:, :-1], O[:, 1:]
    good = (adjacent & np.isfinite(c0) & np.isfinite(o1) & (c0 > 0) & (o1 > 0))
    gap = np.zeros_like(c0)
    gap[good] = np.log(o1[good] / c0[good])
    on_raw[:, :-1] = gap
    on[:, :-1] = gap + np.where(good, dlog_open[:, 1:], 0.0)
    valid[:, :-1] = good

    if not (np.all(np.isfinite(on)) and np.all(np.isfinite(on_raw))):
        raise AssertionError("non-finite overnight return leaked into the grid")

    # how much the strict-adjacency rule costs, so the choice is auditable
    holed = int((panel.live[:, :-1] & ~adjacent).sum())
    return {
        "on_log": on, "on_raw_log": on_raw, "valid": valid,
        "simple": np.expm1(on), "simple_raw": np.expm1(on_raw),
        "nlive": np.maximum(panel.live.sum(axis=0), 1).astype(float),
        "dropped_nonadjacent": holed,
        "priced_nights": int(valid.sum()),
        "unpriced_live_nights": int((panel.live[:, :-1] & ~good).sum()),
    }


def enforce_tradeable(pos, panel, night, start=0):
    """No exposure outside a symbol's window, and NO EXPOSURE ON A NIGHT THE
    BOOK CANNOT PRICE. The second half is the addition: a fee charged for a
    return that does not exist is a fabricated loss, the mirror of contract
    point 4's fabricated price."""
    out = pos * panel.live * night["valid"]
    out[:, :start] = 0.0
    return out


