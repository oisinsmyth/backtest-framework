def _synth():
    """A three-name, six-bar panel with prices chosen so every quantity below is
    known by hand. AAA gaps up then down; BBB is flat overnight and moves only
    intraday, so a close-to-close scorer and an overnight one MUST disagree on
    it; CCC pays a dividend on bar 3."""
    dates = ["2020-01-02", "2020-01-03", "2020-01-06", "2020-01-07",
             "2020-01-08", "2020-01-09"]
    px = {  # (open, close) per bar; high/low are padded around them
        "AAA": [(100.0, 100.0), (101.0, 102.0), (103.0, 100.0), (99.0, 101.0),
                (102.0, 104.0), (105.0, 103.0)],
        "BBB": [(50.0, 50.0), (50.0, 52.0), (52.0, 49.0), (49.0, 51.0),
                (51.0, 53.0), (53.0, 50.0)],
        "CCC": [(20.0, 20.0), (20.0, 21.0), (21.0, 22.0), (21.5, 21.0),
                (21.0, 20.5), (20.5, 21.0)],
    }
    symbols = sorted(px)
    n, T = len(symbols), len(dates)
    closes = np.full((n, T), np.nan)
    live = np.zeros((n, T), dtype=bool)
    cleaned, index_of = {}, {}
    for i, s in enumerate(symbols):
        bars = []
        for t, (o, c) in enumerate(px[s]):
            hi, lo = max(o, c) * 1.01, min(o, c) * 0.99
            bars.append(RP.Stamped(dates[t], RP.Bar(o, hi, lo, c, 1e6)))
            closes[i, t] = c
            live[i, t] = True
        cleaned[s] = bars
        index_of[s] = (0, T - 1)
    logr = np.zeros((n, T))
    logr[:, 1:] = np.diff(np.log(closes), axis=1)
    total = logr.copy()
    div_amt = np.zeros((n, T))
    div_amt[symbols.index("CCC"), 3] = 0.50
    total[symbols.index("CCC"), 3] += math.log1p(0.50 / closes[symbols.index("CCC"), 3])
    panel = RP.RaggedPanel(symbols, dates, closes, logr, total,
                           np.full(n, FEE / 1e4), live, index_of)
    return panel, cleaned, div_amt, px


def selftest() -> int:
    """Arithmetic gates on synthetic bars. NO FIXTURE IS READ AND NO CELL IS
    SCORED -- this validates the machinery, it does not spend the study."""
    print("D282 SELF-TEST -- synthetic bars, no fixture, no cell scored\n")
    panel, cleaned, amt, px = _synth()
    g = P1.build_grids(panel, cleaned)
    symbols = panel.symbols

    # the loader cross-check, on a panel where the answer is known
    dlog_close = np.zeros_like(panel.closes)
    dlog_open = np.zeros_like(panel.closes)
    for i in range(len(symbols)):
        for t in range(len(panel.dates)):
            if amt[i, t] > 0:
                dlog_close[i, t] = math.log1p(amt[i, t] / panel.closes[i, t])
                dlog_open[i, t] = math.log1p(amt[i, t] / g["open"][i, t])
    worst, n_div = assert_dividends_match_loader(panel, dlog_close)
    print(f"  [1] dividend parse matches the loader to {worst:.1e} on {n_div} ex-date bars")

    night = night_grids(panel, g, dlog_open)

    # (2) the compounded quantity, on a name with no dividend
    i = symbols.index("AAA")
    want = math.log(px["AAA"][1][0] / px["AAA"][0][1])       # open(t+1)/close(t)
    got = float(night["on_log"][i, 0])
    assert abs(want - got) < 1e-12, (want, got)
    assert abs(float(night["on_log"][i, len(panel.dates) - 1])) == 0.0
    print(f"  [2] on_log[AAA,0] = log(open(1)/close(0)) = {got:+.6f}; last column is zero")

    # (3) BBB is FLAT overnight and moves intraday. A close-to-close scorer would
    #     book its whole move; the overnight scorer must book none of it.
    j = symbols.index("BBB")
    assert abs(float(night["on_log"][j, 1])) < 1e-12
    assert abs(float(panel.total_log_returns[j, 2])) > 0.05
    print(f"  [3] BBB overnight {night['on_log'][j, 1]:+.6f} against close-to-close "
          f"{panel.total_log_returns[j, 2]:+.6f} -- the two scorers disagree, as they must")

    # (4) the SHORT owes the dividend
    k = symbols.index("CCC")
    raw, tot = float(night["on_raw_log"][k, 2]), float(night["on_log"][k, 2])
    assert tot > raw, (raw, tot)
    assert abs((tot - raw) - math.log1p(0.50 / px["CCC"][3][0])) < 1e-12
    print(f"  [4] CCC ex-div night: raw gap {raw:+.6f}, dividend-charged {tot:+.6f} -- "
          f"a short's move is {1e4 * (raw - tot):+.1f} bp WORSE")

    # (5) two sides of cost per held name-night, and the move statistic
    pos = np.zeros_like(panel.closes)
    pos[i, 1] = -1.0
    pos[i, 2] = -1.0                                        # two consecutive nights
    s = overnight_score(panel, pos, night)
    assert s["trades"] == 2, s["trades"]
    assert abs(s["turnover_units"] - 4.0) < 1e-12, s["turnover_units"]
    assert s["entries_diff_based"] == 1                     # exactly what makes diff() wrong here
    hand = -0.5 * (float(night["simple"][i, 1]) + float(night["simple"][i, 2])) * 1e4
    assert abs(s["mean_move_bp"] - hand) < 1e-9, (s["mean_move_bp"], hand)
    print(f"  [5] two consecutive nights -> trades 2, turnover 4.0 units "
          f"(diff-based entries would say {s['entries_diff_based']}); "
          f"mean move {s['mean_move_bp']:+.2f} bp matches by hand")

    # (6) the cost charged is exactly 2 sides x fee per held name-night
    free = type(panel)(**{**vars(panel), "cost_fraction": np.zeros_like(panel.cost_fraction)})
    gs = overnight_score(free, pos, night, rf_annual=0.0, borrow_annual=0.0)
    want_cost = 2.0 * (FEE / 1e4) * 2.0 / float(night["nlive"][0])
    assert abs(s["cost_paid_pooled"] - want_cost) < 1e-12, (s["cost_paid_pooled"], want_cost)
    assert gs["cost_paid_pooled"] == 0.0
    print(f"  [6] cost charged {s['cost_paid_pooled']:.3e} = 2 sides x {FEE:.0f}bp x 2 nights "
          f"/ {night['nlive'][0]:.0f} live; the gross panel charges zero")

    # (7) L1 catches an UNLAGGED selection -- the D279 defect, injected on purpose
    T = len(panel.dates)
    base = np.zeros_like(panel.closes)
    base[:, 1:] = -1.0
    score = np.array([[9.0, 1.0, 5.0, 2.0, 7.0, 3.0],
                      [1.0, 9.0, 2.0, 5.0, 3.0, 7.0],
                      [5.0, 5.0, 9.0, 9.0, 9.0, 9.0]])
    good = C.top_n(base, score, 1)
    assert audit_lag(base, score, 1, good) == T - 1
    bad = np.zeros_like(base)
    for t in range(1, T):                                   # rank on score[:, t] -- look-ahead
        bad[int(np.argmin(score[:, t])), t] = -1.0
    try:
        audit_lag(base, score, 1, bad)
    except AssertionError:
        print("  [7] audit_lag PASSES the lagged book and RAISES on the unlagged one")
    else:
        raise AssertionError("audit_lag failed to catch an unlagged selection")

    # (8) L3 refuses a grid that IS the close-to-close return. The panel is tiled
    #     only to clear the check's own >=1000-cell floor; no value changes.
    tiled = np.tile(panel.total_log_returns, (400, 1))
    wide = RP.RaggedPanel(list(range(tiled.shape[0])), panel.dates, None, None, tiled,
                          None, np.ones(tiled.shape, dtype=bool), {})
    try:
        assert_not_close_to_close(wide, {"on_log": tiled.copy(),
                                         "valid": np.ones(tiled.shape, dtype=bool)})
    except AssertionError as e:
        assert "CLOSE-TO-CLOSE" in str(e), e
        print("  [8] assert_not_close_to_close REFUSES a grid equal to total_log_returns")
    else:
        raise AssertionError("L3 failed to catch a close-to-close grid")

    # and it PASSES the real overnight grid, which is the other half of the check
    c8, r8, n8 = assert_not_close_to_close(
        RP.RaggedPanel(list(range(tiled.shape[0])), panel.dates, None, None, tiled, None,
                       np.ones(tiled.shape, dtype=bool), {}),
        {"on_log": np.tile(night["on_log"], (400, 1)),
         "valid": np.tile(night["valid"], (400, 1))})
    print(f"      and PASSES the real overnight grid: corr {c8:+.4f}, "
          f"size ratio {r8:.1%} over {n8:,} cells")

    print("\n  ALL SELF-TESTS PASSED. No fixture was read and no cell was scored.")
    return 0


